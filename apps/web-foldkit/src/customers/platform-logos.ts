type Platform = keyof typeof LOGOS

/** The source's names for a platform that differ from ours. */
const ALIASES: ReadonlyMap<string, Platform> = new Map<string, Platform>([
	["twitter", "x"],
	["angellist", "wellfound"],
	["playstore", "googleplay"],
	["google_play", "googleplay"],
	["app_store", "appstore"],
	["ios", "appstore"],
])

/** Hosts that name a platform when the link's type does not. */
const HOSTS: ReadonlyMap<string, Platform> = new Map<string, Platform>([
	["linkedin.com", "linkedin"],
	["x.com", "x"],
	["twitter.com", "x"],
	["github.com", "github"],
	["crunchbase.com", "crunchbase"],
	["youtube.com", "youtube"],
	["apps.apple.com", "appstore"],
	["producthunt.com", "producthunt"],
	["facebook.com", "facebook"],
	["instagram.com", "instagram"],
	["discord.com", "discord"],
	["discord.gg", "discord"],
	["medium.com", "medium"],
	["tiktok.com", "tiktok"],
	["wellfound.com", "wellfound"],
	["angel.co", "wellfound"],
	["play.google.com", "googleplay"],
	["threads.net", "threads"],
	["reddit.com", "reddit"],
])

const isPlatform = (key: string): key is Platform => Object.hasOwn(LOGOS, key)

/** The platform of a link, by its type, else its host; null for one we have no mark for. */
export const platformOf = (type: string, href: string): Platform | null => {
	const key = type.toLowerCase()
	if (isPlatform(key)) return key
	const alias = ALIASES.get(key)
	if (alias !== undefined) return alias
	try {
		const host = new URL(href).hostname.replace(/^www\./, "")
		return HOSTS.get(host) ?? null
	} catch {
		return null
	}
}

export const platformTitle = (platform: Platform): string => LOGOS[platform].title

/** The platform's mark, decorative (the link around it is named). */
export const platformLogo = <M>(h: HtmlBuilder<M>, platform: Platform, className: string): Html => {
	const logo: PlatformLogo = LOGOS[platform]
	return h.svg(
		[
			h.Attribute("viewBox", "0 0 24 24"),
			h.Attribute("xmlns", "http://www.w3.org/2000/svg"),
			h.Attribute("aria-hidden", "true"),
			h.Class(logo.color === null ? `${className} text-fg` : className),
		],
		[h.path([h.Attribute("fill", logo.color ?? "currentColor"), h.Attribute("d", logo.path)])],
	)
}
