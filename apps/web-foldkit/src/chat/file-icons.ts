export const fileIcon = <Message>(
	h: HtmlBuilder<Message>,
	type: string,
	options: { readonly className?: string } = {},
): Html => renderTree(h, (Object.hasOwn(icons, type) ? icons[type] : undefined) ?? icons.empty!, options.className)
