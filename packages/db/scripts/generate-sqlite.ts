/**
 * Writes each store's initial migration from `src/tables`:
 *
 *   bun run db:generate-sqlite
 *
 * `src/migrations.generated.ts` holds the statements `applyMigrations` runs; D1's copy goes to
 * `migrations/directory/0001_initial/migration.sql`, the drizzle-kit layout Alchemy applies.
 */
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { Effect } from "effect"
import { renderStoreSchema } from "../src/schema-ddl"
import { storeNames, storeTables } from "../src/stores"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

const program = Effect.gen(function* () {
	const rendered: Record<string, ReadonlyArray<string>> = {}
	for (const store of storeNames) rendered[store] = yield* renderStoreSchema(storeTables[store])

	const body = storeNames
		.map(
			(store) =>
				`\t${store}: [\n${rendered[store]!.map((s) => `\t\t${JSON.stringify(s)},\n`).join("")}\t],\n`,
		)
		.join("")
	writeFileSync(
		join(root, "src/migrations.generated.ts"),
		`// Generated by \`bun run db:generate-sqlite\` from src/tables. Do not edit.\n\nexport const initialStatements = {\n${body}} as const\n`,
	)

	const d1Dir = join(root, "migrations/directory/0001_initial")
	mkdirSync(d1Dir, { recursive: true })
	writeFileSync(
		join(d1Dir, "migration.sql"),
		`${rendered.directory!.join(";\n--> statement-breakpoint\n")};\n`,
	)
	yield* Effect.log(`Wrote ${storeNames.map((s) => `${s}: ${rendered[s]!.length}`).join(", ")} statements`)
})

Effect.runPromise(program).catch((error) => {
	console.error(error)
	process.exit(1)
})
