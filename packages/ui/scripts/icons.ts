import { spawnSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import * as Icons from "../../../apps/web-foldkit/src/icons/index.ts"
import { iconNames, iconSources, type IconName } from "../src/vocabulary/options.ts"

/**
 * `bun scripts/icons.ts`: writes `src/web/icons.generated.ts`, the web's own icons
 * (`apps/web-foldkit/src/icons`, one per `IconName` via `iconSources`) as SVG markup. Each icon is
 * built once with a stub of Foldkit's `h`. `--check` writes nothing and exits 1 when the file is stale.
 */

interface Node {
	readonly tag: string
	readonly attrs: ReadonlyArray<readonly [string, string]>
	readonly children: ReadonlyArray<Node | string>
}

const attribute = (name: string, value: string) => [name, value] as const
const stub = new Proxy(
	{},
	{
		get: (_, key: string) => {
			if (key === "Attribute") return attribute
			if (key === "Class") return (value: string) => attribute("class", value)
			return (
				attrs: ReadonlyArray<readonly [string, string]> = [],
				children: ReadonlyArray<Node | string> = [],
			): Node => ({ tag: key, attrs, children })
		},
	},
)

const escape = (value: string) =>
	value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;")

// Sizing comes from the recipe (`[data-hz=icon] > svg` fills its box), so the fixed size is dropped.
const dropped = new Set(["class", "data-slot", "width", "height"])

const markup = (node: Node | string): string => {
	if (typeof node === "string") return escape(node)
	if (node.tag === "title") return ""
	const attrs = node.attrs
		.filter(([name]) => !dropped.has(name))
		.map(([name, value]) => ` ${name}="${escape(value)}"`)
		.join("")
	return `<${node.tag}${attrs}>${node.children.map(markup).join("")}</${node.tag}>`
}

const build = (name: IconName) => {
	// SAFETY: the stub stands in for Foldkit's `HtmlBuilder`; an icon only calls `h.<tag>` and
	// `h.Attribute`, so what it returns is the stub's `Node` tree.
	const make = Icons[iconSources[name]] as unknown as (h: typeof stub) => Node
	return markup(make(stub))
}

const key = (name: string) => (/^[a-z]\w*$/i.test(name) ? name : JSON.stringify(name))

const output = resolve(import.meta.dirname, "../src/web/icons.generated.ts")
const root = resolve(import.meta.dirname, "../../..")

// Through the repo's formatter, so `--check` and `format:check` agree on the file's shape.
const formatted = (source: string) => {
	const run = spawnSync(resolve(root, "node_modules/.bin/oxfmt"), [`--stdin-filepath=${output}`], {
		cwd: root,
		input: source,
		encoding: "utf8",
	})
	if (run.status !== 0) throw new Error(`oxfmt failed: ${run.stderr}`)
	return run.stdout
}

const generateIcons = () =>
	formatted(
		[
			"// Generated by `bun scripts/icons.ts` from `apps/web-foldkit/src/icons`; do not edit.",
			'import type { IconName } from "../vocabulary/options.ts"',
			"",
			"/** Each `IconName`'s SVG markup, sized by its container (no width or height). */",
			"export const iconSvgs = {",
			...iconNames.map((name) => `\t${key(name)}: ${JSON.stringify(build(name))},`),
			"} satisfies { readonly [Name in IconName]: string }",
			"",
		].join("\n"),
	)

const read = (path: string) => {
	try {
		return readFileSync(path, "utf8")
	} catch {
		return undefined
	}
}

if (import.meta.main) {
	const content = generateIcons()
	if (process.argv.includes("--check")) {
		if (read(output) !== content) {
			console.error(`${output} is stale; run bun scripts/icons.ts`)
			process.exit(1)
		}
		console.log(`icons are current (${iconNames.length} icons)`)
	} else {
		writeFileSync(output, content)
		console.log(`${iconNames.length} icons -> ${output}`)
	}
}
