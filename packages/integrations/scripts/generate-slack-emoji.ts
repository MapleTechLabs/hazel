/// <reference types="node" />
/**
 * Writes `src/slack/emoji-data.generated.ts`, the compact Slack short name ⇄ unicode table, from
 * iamcal/emoji-data (npm `emoji-datasource`), the dataset Slack's emoji names come from.
 *
 *   bun packages/integrations/scripts/generate-slack-emoji.ts [path/to/emoji.json]
 *
 * Without a path it downloads `emoji.json` of the pinned version below.
 */
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const EMOJI_DATASOURCE_VERSION = "16.0.0"
const SOURCE_URL = `https://cdn.jsdelivr.net/npm/emoji-datasource@${EMOJI_DATASOURCE_VERSION}/emoji.json`
const OUTPUT = fileURLToPath(new URL("../src/slack/emoji-data.generated.ts", import.meta.url))

/** Fitzpatrick modifiers, Slack's `skin-tone-2` .. `skin-tone-6`. */
const SKIN_TONES = ["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"] as const

interface SkinVariation {
	readonly unified: string
}

interface EmojiEntry {
	readonly unified: string
	readonly short_name: string
	readonly short_names: ReadonlyArray<string>
	readonly sort_order: number
	readonly skin_variations?: Record<string, SkinVariation>
}

const toEmoji = (unified: string): string =>
	String.fromCodePoint(...unified.split("-").map((hex) => Number.parseInt(hex, 16)))

/** The toned form `slackEmojiToUnicode` derives: the modifier after the first code point, minus a VS16. */
const deriveToned = (unified: string, tone: string): string => {
	const [first, ...rest] = unified.split("-")
	const tail = rest[0] === "FE0F" ? rest.slice(1) : rest
	return [first, tone, ...tail].join("-")
}

const loadEntries = async (path: string | undefined): Promise<ReadonlyArray<EmojiEntry>> => {
	if (path) {
		return JSON.parse(await readFile(path, "utf8")) as ReadonlyArray<EmojiEntry>
	}
	const response = await fetch(SOURCE_URL)
	if (!response.ok) {
		throw new Error(`Fetching ${SOURCE_URL} failed with status ${response.status}`)
	}
	return (await response.json()) as ReadonlyArray<EmojiEntry>
}

/**
 * The skin tone column: 1 when every tone is derivable with `deriveToned`, the five toned emoji
 * when the emoji only takes a tone per person (people_holding_hands), absent when it takes none.
 * Mixed-tone pairs (`1F3FB-1F3FC`) are left out.
 */
const skinTones = (entry: EmojiEntry): 1 | ReadonlyArray<string> | undefined => {
	const variations = entry.skin_variations
	if (!variations) return undefined
	if (SKIN_TONES.every((tone) => variations[tone]?.unified === deriveToned(entry.unified, tone))) {
		return 1
	}
	const doubled = SKIN_TONES.map((tone) => variations[`${tone}-${tone}`] ?? variations[tone])
	if (doubled.every((variation) => variation !== undefined)) {
		return doubled.map((variation) => toEmoji(variation.unified))
	}
	return undefined
}

const main = async () => {
	const entries = [...(await loadEntries(process.argv[2]))].sort((a, b) => a.sort_order - b.sort_order)
	const rows = entries.map((entry) => {
		const names = [entry.short_name, ...entry.short_names.filter((name) => name !== entry.short_name)]
		const tones = skinTones(entry)
		const row: Array<unknown> = [names.join(" "), toEmoji(entry.unified)]
		if (tones !== undefined) row.push(tones)
		return `\t${JSON.stringify(row)},`
	})

	const source = [
		`// Generated by scripts/generate-slack-emoji.ts from emoji-datasource@${EMOJI_DATASOURCE_VERSION}. Do not edit.`,
		"",
		"/**",
		" * `[short names, emoji, skin tones?]`: the names space-separated, Slack's canonical one first.",
		" * Skin tones: 1 = derived (the modifier after the first code point), or the five toned emoji",
		" * (`skin-tone-2` .. `skin-tone-6`); absent = takes no skin tone.",
		" */",
		"export type SlackEmojiRow = readonly [names: string, emoji: string, tones?: 1 | ReadonlyArray<string>]",
		"",
		"export const SLACK_EMOJI_ROWS: ReadonlyArray<SlackEmojiRow> = [",
		...rows,
		"]",
		"",
	].join("\n")

	await writeFile(OUTPUT, source)
	console.log(`Wrote ${rows.length} emoji to ${OUTPUT}`)
}

await main()
